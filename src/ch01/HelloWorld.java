public class HelloWorld {

    public static void main(String[] args) {

        System.out.println("Hello World");
        System.out.println();

        // 화면에 0~9까지 출력
        System.out.println(0); // Ctrl+D로 명령어 복사
        System.out.println(1); // Ctrl+D로 명령어 복사
        System.out.println(2); // Ctrl+D로 명령어 복사
        System.out.println(3); // Ctrl+D로 명령어 복사
        System.out.println(4); // Ctrl+D로 명령어 복사
        System.out.println(5); // Ctrl+D로 명령어 복사
        System.out.println(6); // Ctrl+D로 명령어 복사
        System.out.println(7); // Ctrl+D로 명령어 복사
        System.out.println(8); // Ctrl+D로 명령어 복사
        System.out.println(9); // Ctrl+D로 명령어 복사

    } // end of main

} // end of class