package ch05;

/**
 * 관계연산자
 *  연산의 결과는 true or false로 반환된다
 */
public class Operation5 {
    public static void main(String[] args) {

        int num1 = 5;
        int num2 = 3;

        boolean result1 = num1 > num2;

        System.out.println(num1 > num2);
        System.out.println(num1 < num2);
        System.out.println(num1 >= num2);
        System.out.println(num1 <= num2);
        System.out.println(num1 == num2);
        System.out.println(num1 != num2);


    }
}
